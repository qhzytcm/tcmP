add('原文', '12.2.1.1', '黄帝问曰：人有重身，九月而瘖，此为何也？岐伯对曰：胞之络脉绝也。帝曰：何以言之？岐伯曰：胞络者系于肾，少阴之脉，贯肾系舌本，故不能言。帝曰：治之奈何？岐伯曰：无治也，当十月复。《刺法》曰：无损不足，益有余，以成其疹，然后调之。')
