add('原文', '12.2.1.4', '帝曰：人有尺脉数甚，筋急而见，此为何病？岐伯曰：此所谓疹筋，是人腹必急，白色黑色见，则病甚。')
add('原文', '12.2.1.5', '帝曰：人有病头痛以数岁不已，此安得之，名为何病？岐伯曰：当有所犯大寒，内至骨髓，髓者以脑为主，脑逆故令头痛，齿亦痛，病名曰厥逆。帝曰：善。')
add('原文', '12.2.1.6', '帝曰：有病口甘者，病名为何？何以得之？岐伯曰：此五气之溢也，名曰脾瘅。夫五味入口，藏于胃，脾为之行其精气，津液在脾，故令人口甘也。此肥美之所发也。此人必数食甘美而多肥也。肥者令人内热，甘者令人中满，故其气上溢，转为消渴。治之以兰，除陈气也。')
