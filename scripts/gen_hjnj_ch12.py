# ── 12.4 脉解（第49篇）──
add('篇名', '12.4', '脉解（素问第49篇）')
add('通读', '12.4.0', '通读：本篇以十二月与三阴三阳经脉相配，逐经解说经脉病候之病机（太阳所谓肿腰脽痛者，正月太阳寅，寅太阳也），提出"所谓甚则狂巅疾者，阳尽在上而阴气从下，下虚上实"等经脉病解，为"经脉-时令-病机"对应之专论。')
add('原文', '12.4.1.1', '太阳所谓肿腰脽痛者，正月太阳寅，寅太阳也。正月阳气出在上，而阴气盛，阳未得自次也，故肿腰脽痛也。病偏虚为跛者，正月阳气冻解，地气而出也。所谓偏虚者，冬寒颇有不足者，故偏虚为跛也。所谓强上引背者，阳气大上而争，故强上也。所谓耳鸣者，阳气万物盛上而跃，故耳鸣也。所谓甚则狂巅疾者，阳尽在上而阴气从下，下虚上实，故狂巅疾也。所谓浮为聋者，皆在气也。所谓入中为瘖者，阳盛已衰，故为瘖也。内夺而厥，则为瘖俳，此肾虚也。少阴不至者，厥也。')
add('原文', '12.4.1.2', '少阳所谓心胁痛者，言少阳盛也，盛者心之所表也。九月阳气尽而阴气盛，故心胁痛也。所谓不可反侧者，阴气藏物也，物藏则不动，故不可反侧也。所谓甚则跃者，九月万物尽衰，草木毕落而堕，则气去阳而之阴，气盛而阳之下长，故谓跃。')
add('原文', '12.4.1.3', '阳明所谓洒洒振寒者，阳明者午也，五月盛阳之阴也，阳盛而阴气加之，故洒洒振寒也。所谓胫肿而股不收者，是五月盛阳之阴也，阳者衰于五月，而一阴气上，与阳始争，故胫肿而股不收也。所谓上喘而为水者，阴气下而复上，上则邪客于藏府间，故为水也。所谓胸痛少气者，水气在藏府也，水者阴气也，阴气在中，故胸痛少气也。')
add('原文', '12.4.1.4', '太阴所谓病胀者，太阴子也，十一月万物气皆藏于中，故曰病胀。所谓上走心为噫者，阴盛而上走于阳明，阳明络属心，故曰上走心为噫也。所谓食则呕者，物盛满而上溢，故呕也。所谓得后与气则快然如衰者，十二月阴气下衰，而阳气且出，故曰得后与气则快然如衰也。')
add('原文', '12.4.1.5', '少阴所谓腰痛者，少阴者肾也，十月万物阳气皆伤，故腰痛也。所谓呕咳上气喘者，阴气在下，阳气在上，诸阳气浮，无所依从，故呕咳上气喘也。所谓色色不能久立久坐，起则目䀮䀮无所见者，万物阴阳不定未有主也。秋气始至，微霜始下，而方杀万物，阴阳内夺，故目䀮䀮无所见也。所谓少气善怒者，阳气不治，阳气不治则阳气不得出，肝气当治而未得，故善怒。善怒者，名曰煎厥。所谓恐如人将捕之者，秋气万物未有毕去，阴气少，阳气入，阴阳相薄，故恐也。所谓恶闻食臭者，胃无气，故恶闻食臭也。所谓面黑如地色者，秋气内夺，故变于色也。所谓咳则有血者，阳脉伤也。阳气未盛于上而脉满，满则咳，故血见于鼻也。')
add('原文', '12.4.1.6', '厥阴所谓疝妇人少腹肿者，厥阴者辰也，三月阳中之阴，邪在中，故曰疝少腹肿也。所谓腰脊痛不可以俯仰者，三月一振，荣华万物，一俯而不仰也。所谓㿉癃疝肤胀者，曰阴亦盛而脉胀不通，故曰㿉癃疝也。所谓甚则嗌干热中者，阴阳相薄而热，故嗌干也。')
add('注释', '12.4.1.7', '"太阳所谓肿腰脽痛者，正月太阳寅"：以十二月建配三阴三阳经脉释病候——①以"寅月阳气出在上而阴气盛"释太阳正月病（通行）；②有学者认为十二月配经脉之说与《阴阳系日月》等篇偶有龃龉，或为古代历算与医学之交叉记录——并存（非零和局）。又"内夺而厥，则为瘖俳"——肾虚致瘖（失音）伴肢体痿废，为"肾主声"理论之临床表达。')

