add('原文', '3.2.1.3', '帝曰：余已闻六六九九之会也，夫子言积气盈闰，愿闻何谓气？请夫子发蒙解惑焉。岐伯曰：此上帝所秘，先师传之也。帝曰：请遂闻之。岐伯曰：五日谓之候，三候谓之气，六气谓之时，四时谓之岁，而各从其主治焉。五运相袭，而皆治之，终期之日，周而复始，时立气布，如环无端，候亦同法。故曰：不知年之所加，气之盛衰，虚实之所起，不可以为工矣。')
