# ── 3.4 五脏别论（第11篇）──
add('篇名', '3.4', '五脏别论（素问第11篇）')
add('原文', '3.4.1.1', '黄帝问曰：余闻方士，或以脑髓为藏，或以肠胃为藏，或以为府。敢问更相反，皆自谓是。不知其道，愿闻其说。岐伯对曰：脑、髓、骨、脉、胆、女子胞，此六者，地气之所生也，皆藏于阴而象于地，故藏而不写，名曰奇恒之府。夫胃、大肠、小肠、三焦、膀胱，此五者，天气之所生也，其气象天，故写而不藏。此受五藏浊气，名曰传化之府，此不能久留，输写者也。魄门亦为五藏使，水谷不得久藏。所谓五藏者，藏精气而不写也，故满而不能实。六府者，传化物而不藏，故实而不能满也。所以然者，水谷入口，则胃实而肠虚；食下，则肠实而胃虚。故曰：实而不满，满而不实也。')
add('原文', '3.4.1.2', '帝曰：气口何以独为五藏主？岐伯曰：胃者，水谷之海，六府之大源也。五味入口，藏于胃，以养五藏气。气口亦太阴也，是以五藏六府之气味，皆出于胃，变见于气口。故五气入鼻，藏于心肺，心肺有病，而鼻为之不利也。凡治病必察其下，适其脉，观其志意，与其病也。')
add('原文', '3.4.1.3', '拘于鬼神者，不可与言至德；恶于针石者，不可与言至巧。病不许治者，病必不治，治之无功矣。')
add('注释', '3.4.1.4', '“藏而不写/写而不藏”“满而不能实/实而不能满”：藏府功能之别，历代无异说。然“奇恒之府”之“奇恒”——①以“异于恒常之府”释；②以“形似府而功似藏”释——措辞略异，理则相通。又“凡治病必察其下”之“下”——或释“二便”，或释“下焦”，或释“病之下部” ——三说并存（非零和局）。')

