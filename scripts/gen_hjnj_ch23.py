add('通读', '23.5.0', '通读：本篇论杂病之刺法——"厥挟脊而痛者至顶，头沉沉然，目䀮䀮然，腰脊强，取足太阳腘中血络"等厥/嗌干/喉痹/疟/齿痛/聋/衄/腰痛/心痛/喜怒/狂/痿厥/哕/呕/大小便等杂病之取穴（刺足太阳/阳明/少阴等），为临床各科刺法之汇编。')
add('原文', '23.5.1.1', '厥挟脊而痛者至顶，头沉沉然，目䀮䀮然，腰脊强，取足太阳腘中血络。厥胸满面肿，唇漯漯然，暴言难，甚则不能言，取足阳明。厥气走喉而不能言，手足清，大便不利，取足少阴。厥而腹向向然，多寒气，腹中縠縠，便溲难，取足太阴。')
add('原文', '23.5.1.2', '嗌干，口中热如胶，取足少阴。膝中痛，取犊鼻，以员利针，发而间之。针大如氂，刺膝无疑。')
add('原文', '23.5.1.3', '喉痹不能言，取足阳明；能言，取手阳明。疟不渴，间日而作，取足阳明；渴而日作，取手阳明。齿痛，不恶清饮，取足阳明；恶清饮，取手阳明。聋而不痛者，取足少阳；聋而痛者，取手阳明。衄而不止，衃血流，取足太阳；衃血，取手太阳。不已，刺宛骨下，不已，刺腘中出血。')
add('原文', '23.5.1.4', '腰痛，痛上寒，取足太阳阳明；痛上热，取足厥阴；不可以俛仰，取足少阳。中热而喘，取足少阴，腘中血络。喜怒而不欲食，言益小，刺足太阴。怒而多言，刺足少阳。顑痛，刺手阳明与顑之盛脉出血。项痛不可俛仰，刺足太阳；不可以顾，刺手太阳也。')
add('原文', '23.5.1.5', '小腹满大，上走胃，至心，淅淅身时寒热，小便不利，取足厥阴。腹满，大便不利，腹大，亦上走胸嗌，喘息喝喝然，取足少阴。腹满食不化，腹向向然，不能大便，取足太阴。')
add('原文', '23.5.1.6', '心痛引腰脊，欲呕，取足少阴。心痛，腹胀，啬啬然，大便不利，取足太阴。心痛引背不得息，刺足少阴；不已，取手少阳。心痛引小腹满，上下无常处，便溲难，刺足厥阴。心痛，但短气不足以息，刺手太阴。')
add('原文', '23.5.1.7', '心痛，当九节刺之，按已刺按之，立已；不已，上下求之，得之立已。')
add('原文', '23.5.1.8', '顑痛，刺足阳明曲周动脉，见血，立已；不已，按人迎于经，立已。气逆上，刺膺中陷者与下胸动脉。')
add('原文', '23.5.1.9', '腹痛，刺脐左右动脉，已刺按之，立已；不已，刺气街，已刺按之，立已。')
add('原文', '23.5.1.10', '痿厥为四末束悗，乃疾解之，日二，不仁者十日而知，无休，病已止。')
add('原文', '23.5.1.11', '哕，以草刺鼻，嚏，嚏而已；无息而疾迎引之，立已；大惊之，亦可已。')
add('原文', '23.5.1.12', '呕，有脓者，不可治呕，脓尽自愈。不得息而呕，取足少阴。呕甚则长虫出，取足阳明。')
add('原文', '23.5.1.13', '气满上，呼吸迫，取足太阴经，至急刺之。寒，取之荥输，深刺之，取之经。')
add('原文', '23.5.1.14', '喜怒而不欲食，言益小，刺足太阴。怒而多言，刺足少阳。')
add('原文', '23.5.1.15', '聂辟气不足，息短不属，动作气索，补足少阴，去血络也。')
add('注释', '23.5.1.16', '本篇注释：①杂病刺法之汇编（通行）——"嗌干取足少阴""齿痛取手足阳明""聋取手足少阳阳明"等，为经络辨证取穴之临床示范。②"哕，以草刺鼻，嚏，嚏而已"——以嚏止哕之古法（通行），为"嚏以宣发"之应用。③"呕，有脓者，不可治呕，脓尽自愈"——呕脓之治（通行）。④"痿厥为四末束悗，乃疾解之"——束缚四末以治痿厥之古法，其法今罕用，**悬疑存疑**。')

# ═══ 23.6 周痹（灵枢第27篇）═══
add('篇名', '23.6', '周痹（灵枢第27篇）')
add('通读', '23.6.0', '通读：本篇辨周痹与众痹——"周痹之在身也，上下移徙随脉，其上下左右相应，间不容空"（周痹随脉上下）与"众痹各在其处，更发更止，更居更起，以右应左，以左应右"（众痹各处发作），提出"此各在其处，更发更止……刺此者，痛虽已止，必刺其处，勿令复起"之刺法与"周痹者，在于血脉之中，随脉以上，随脉以下，不能左右，各当其所"之病机，为痹证鉴别之专论。')
add('原文', '23.6.1.1', '黄帝问于岐伯曰：周痹之在身也，上下移徙随脉，其上下左右相应，间不容空，愿闻此痛，在血脉之中邪？将在分肉之间乎？何以致是？其痛之移也，间不及下针，其慉痛之时，不及定治，而痛已止矣，何道使然？愿闻其故。')
add('原文', '23.6.1.2', '岐伯答曰：此众痹也，非周痹也。')
add('原文', '23.6.1.3', '黄帝曰：愿闻众痹。岐伯对曰：此各在其处，更发更止，更居更起，以右应左，以左应右，非能周也，更发更休也。')
add('原文', '23.6.1.4', '黄帝曰：善。刺之奈何？岐伯对曰：刺此者，痛虽已止，必刺其处，勿令复起。')
add('原文', '23.6.1.5', '帝曰：善。愿闻周痹何如？岐伯对曰：周痹者，在于血脉之中，随脉以上，随脉以下，不能左右，各当其所。')
add('原文', '23.6.1.6', '黄帝曰：刺之奈何？岐伯对曰：痛从上下者，先刺其下以过之，后刺其上以脱之；痛从下上者，先刺其上以过之，后刺其下以脱之。')
add('原文', '23.6.1.7', '黄帝曰：善。此痛安生？何因而有名？岐伯对曰：风寒湿气，客于外分肉之间，迫切而为沫，沫得寒则聚，聚则排分肉而分裂也，分裂则痛，痛则神归之，神归之则热，热则痛解，痛解则厥，厥则他痹发，发则如是。')
add('原文', '23.6.1.8', '帝曰：善。余已得其意矣。此内不在藏，而外未发于皮，独居分肉之间，真气不能周，故名曰周痹。故刺痹者，必先切循其下之六经，视其虚实，及大络之血结而不通，及虚而脉陷空者而调之，熨而通之，其瘛坚，转引而行之。')
add('注释', '23.6.1.9', '本篇注释：①众痹（更发更止，各处发作）与周痹（随脉上下移徙）之辨（通行）。②"风寒湿气，客于外分肉之间，迫切而为沫"——痹痛之病机（沫聚排分肉）（通行）。③"此内不在藏，而外未发于皮，独居分肉之间，真气不能周，故名曰周痹"——周痹命名之由（通行）。④"刺痹者，必先切循其下之六经……熨而通之"——痹证调治总则（通行）。')

# ═══ 23.7 口问（灵枢第28篇）═══
add('篇名', '23.7', '口问（灵枢第28篇）')
add('通读', '23.7.0', '通读：本篇论"口问"（闲居而问）之十二邪——"夫百病之始生也，皆生于风雨寒暑，阴阳喜怒，饮食居处，大惊卒恐"，详述欠（卫气昼行于阳，夜半入阴）、哕（谷入于胃，胃气上注于肺）、唏（阴盛阳绝）、振寒（寒气客于皮肤）、噫（寒气客于胃）、嚏（阳气和利满于心）、泣（心者五脏六腑之主也）、太息（忧思则心系急）、涎下（饮食者皆入于胃）、耳鸣（上气不足）、啮舌（厥气走上）等十二邪之病机与补写刺法，为"闲居问答"体之病机专论。')
add('原文', '23.7.1.1', '黄帝闲居，辟左右而问于岐伯曰：余已闻九针之经，论阴阳逆顺六经已毕，愿闻口问。岐伯避席再拜曰：善乎哉问也！此先师之所口传也。')
add('原文', '23.7.1.2', '黄帝曰：愿闻口传。岐伯答曰：夫百病之始生也，皆生于风雨寒暑，阴阳喜怒，饮食居处，大惊卒恐，则血气分离，阴阳破散，经络厥绝，脉道不通，阴阳相逆，卫气稽留，经脉虚空，血气不次，乃失其常。论不在经者，请道其方。')
add('原文', '23.7.1.3', '黄帝曰：人之欠者，何气使然？岐伯答曰：卫气昼日行于阳，夜半则行于阴。阴者主夜，夜者卧。阳者主上，阴者主下。故阴气积于下，阳气未尽，阳引而上，阴引而下，阴阳相引，故数欠。再阳气尽，阴气盛，则目瞑；阴气尽而阳气盛，则寤矣。写足少阴，补足太阳。')
add('原文', '23.7.1.4', '黄帝曰：人之哕者，何气使然？岐伯曰：谷入于胃，胃气上注于肺。今有故寒气与新谷气，俱还入于胃，新故相乱，真邪相攻，气并相逆，复出于胃，故为哕。补手太阴，写足少阴。')
add('原文', '23.7.1.5', '黄帝曰：人之唏者，何气使然？岐伯曰：此阴气盛而阳气虚，阴气疾而阳气徐，阴气盛而阳气绝，故为唏。补足太阳，写足少阴。')
add('原文', '23.7.1.6', '黄帝曰：人之振寒者，何气使然？岐伯曰：寒气客于皮肤，阴气盛，阳气虚，故为振寒寒栗。补诸阳。')
add('原文', '23.7.1.7', '黄帝曰：人之噫者，何气使然？岐伯曰：寒气客于胃，厥逆从下上散，复出于胃，故为噫。补足太阴阳明，一曰补眉本也。')
add('原文', '23.7.1.8', '黄帝曰：人之嚏者，何气使然？岐伯曰：阳气和利，满于心，出于鼻，故为嚏。补足太阳荥眉本，一曰眉上也。')
add('原文', '23.7.1.9', '黄帝曰：人之亸者，何气使然？岐伯曰：胃不实则诸脉虚，诸脉虚则筋脉懈惰，筋脉懈惰则行阴用力，气不能复，故为亸。因其所在，补分肉间。')
add('原文', '23.7.1.10', '黄帝曰：人之哀而泣涕出者，何气使然？岐伯曰：心者，五藏六府之主也；目者，宗脉之所聚也，上液之道也；口鼻者，气之门户也。故悲哀愁忧则心动，心动则五藏六府皆摇，摇则宗脉感，宗脉感则液道开，液道开故泣涕出焉。液者，所以灌精濡空窍者也。故上液之道开则泣，泣不止则液竭，液竭则精不灌，精不灌则目无所见矣，故命曰夺精。补天柱经侠颈。')
add('原文', '23.7.1.11', '黄帝曰：人之太息者，何气使然？岐伯曰：忧思则心系急，心系急则气道约，约则不利，故太息以伸出之。补手少阴心主，足少阳留之也。')
add('原文', '23.7.1.12', '黄帝曰：人之涎下者，何气使然？岐伯曰：饮食者皆入于胃，胃中有热则虫动，虫动则胃缓，胃缓则廉泉开，故涎下。补足少阴。')
add('原文', '23.7.1.13', '黄帝曰：人之耳中鸣者，何气使然？岐伯曰：耳者，宗脉之所聚也，故胃中空则宗脉虚，虚则下溜，脉有所竭者，故耳鸣。补客主人，手大指爪甲上与肉交者也。')
add('原文', '23.7.1.14', '黄帝曰：人之自啮舌者，何气使然？岐伯曰：此厥逆走上，脉气辈至也。少阴气至则啮舌，少阳气至则啮颊，阳明气至则啮唇矣。视主病者则补之。')
add('原文', '23.7.1.15', '凡此十二邪者，皆奇邪之走空窍者也。故邪之所在，皆为不足。故上气不足，脑为之不满，耳为之苦鸣，头为之苦倾，目为之眩。中气不足，溲便为之变，肠为之苦鸣。下气不足，则乃为痿厥心悗。补足外踝下留之。')
add('原文', '23.7.1.16', '黄帝曰：治之奈何？岐伯曰：肾主为欠，取足少阴。肺主为哕，取手太阴。心主为噫，取足太阴。脾主为吞，取足太阴阳明。肝主为泣，取足厥阴。胆主为太息，取足少阳。膀胱主为亸，取足太阳。胃主为涎，取足阳明。小肠主为嗌干，取足太阳。大肠主为齿，取手阳明。三焦主为啮舌，取手少阳。诸脉主为振寒，取足太阳。此十二邪者，各以其经主之。')
add('注释', '23.7.1.17', '本篇注释：①"十二邪"（欠/哕/唏/振寒/噫/嚏/亸/泣/太息/涎下/耳鸣/啮舌）之病机——"奇邪之走空窍者也"，为病机分析之经典（通行）。②"心者，五藏六府之主也；目者，宗脉之所聚也"——悲哀泣涕之机理（通行）。③"上气不足……耳为之苦鸣"等上中下气不足之候（通行），为"上气不足"（清阳不升）理论之渊源。④"肾主为欠……此十二邪者，各以其经主之"——十二邪分属十二经（通行）。⑤"人之亸者"之"亸"（懈惰不收）与"唏"（抽噎）等字训，历代或有异说，**并存（非零和局）**。')

