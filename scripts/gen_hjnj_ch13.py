add('篇名', '13.6', '长刺节论（素问第55篇）')
add('通读', '13.6.0', '通读：本篇论"刺节"之长远治法——头痛、寒热、病大风（骨节重）、病在诸阳脉、病在少腹、病在筋、病在肌肤、病在骨、病在诸阳且寒且热等之刺法（刺皮/刺筋/刺骨之分），为"分部刺治"之专论。')
add('原文', '13.6.1.1', '刺家不诊，听病者言。在头，头疾痛，为藏针之，刺至骨病已，上无伤骨肉及皮，皮者道也。阴刺，入一傍四处，治寒热。深专者，刺大藏，迫藏刺背，背俞也。刺之迫藏，藏会，腹中寒热去而止。与刺之要，发针而浅出血。')
add('原文', '13.6.1.2', '治腐肿者刺腐上，视痈小大深浅刺，刺大者多血，小者深之，以端内针，为故止。')
