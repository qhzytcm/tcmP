add('原文', '13.6.1.4', '病在筋，筋挛节痛，不可以行，名曰筋痹。刺筋上为故，刺分肉间，不可中骨也。病起筋炅，病已止。病在肌肤，肌肤尽痛，名曰肌痹，伤于寒湿。刺大分小分，多发针而深之，以热为故。病在骨，骨重不可举，骨髓酸痛，寒气至，名曰骨痹。深者刺无伤脉肉为故，其道大分小分，骨热病已止。')
add('原文', '13.6.1.5', '病在诸阳脉，且寒且热，诸分且寒且热，名曰狂。刺之虚脉，视分尽热，病已止。病初发岁一发，不治月一发，不治月四五发，名曰癫病。刺诸分诸脉，其无寒者，以针调之，病已止。病风且寒且热，炅汗出，一日数过，先刺诸分理络脉。汗出且寒且热，三日一刺，百日而已。')
