add('原文', '13.4.1.1', '黄帝问曰：愿闻虚实之要。岐伯对曰：气实形实，气虚形虚，此其常也，反此者病。谷盛气盛，谷虚气虚，此其常也，反此者病。脉实血实，脉虚血虚，此其常也，反此者病。')
add('原文', '13.4.1.2', '帝曰：如何而反？岐伯曰：气虚身热，此谓反也。谷入多而气少，此谓反也。谷不入而气多，此谓反也。脉盛血少，此谓反也。脉少血多，此谓反也。气盛身寒，得之伤寒。气虚身热，得之伤暑。谷入多而气少者，得之有所脱血，湿居下也。谷入少而气多者，邪在胃及与肺也。脉小血多者，饮中热也。脉大血少者，脉有风气，水浆不入，此之谓也。')
add('原文', '13.4.1.3', '夫实者，气入也。虚者，气出也。气实者，热也。气虚者，寒也。入实者，左手开针空也。入虚者，左手闭针空也。')
add('注释', '13.4.1.4', '"气实形实，气虚形虚，此其常也，反此者病"：虚实逆从之总纲。①以形气相应为常释（通行）；②"谷入多而气少，得之有所脱血，湿居下也"——血脱湿聚之机理，诸家无异说。又"入实者，左手开针空；入虚者，左手闭针空"——补写针法（开阖补写），历代针派操作略异，并存（非零和局）。')

# ── 13.5 针解（第54篇）──
add('篇名', '13.5', '针解（素问第54篇）')
add('通读', '13.5.0', '通读：本篇为《九针十二原》等针经之注解——释"虚实之要，九针最妙"与"补写之时，以针为之"等文，并解"刺实须其虚者，留针阴气隆至，乃去针也"之补写操作，为内经自注针法之专篇。')
add('原文', '13.5.1.1', '黄帝问曰：愿闻九针之解，虚实之道。岐伯对曰：刺虚则实之者，针下热也，气实乃热也。满而泄之者，针下寒也，气虚乃寒也。菀陈则除之者，出恶血也。邪胜则虚之者，出针勿按。徐而疾则实者，徐出针而疾按之。疾而徐则虚者，疾出针而徐按之。言实与虚者，寒温气多少也。若无若有者，疾不可知也。审后与先者，知病先后也。为虚与实者，工勿失其法。若得若失者，离其法也。虚实之要，九针最妙者，为其各有所宜也。补写之时，以针为之者，与气开阖相合也。')
add('原文', '13.5.1.2', '九针之名，各不同形者，针穷其所当补写也。刺实须其虚者，留针阴气隆至，乃去针也。刺虚须其实者，阳气隆至，针下热乃去针也。经气已至，慎守勿失者，勿变更也。深浅在志者，知病之内外也。近远如一者，深浅其候等也。如临深渊者，不敢堕也。手如握虎者，欲其壮也。神无营于众物者，静志观病人，无左右视也。义无邪下者，欲端以正也。必正其神者，欲瞻病人目制其神，令气易行也。')
add('原文', '13.5.1.3', '所谓三里者，下膝三寸也。所谓跗之者，举膝分易见也。巨虚者，跷足胻独陷者。下廉者，陷下者也。')
add('原文', '13.5.1.4', '帝曰：余闻九针上应天地四时阴阳，愿闻其方，令可传于后世以为常也。岐伯曰：夫一天、二地、三人、四时、五音、六律、七星、八风、九野，身形亦应之。针各有所宜，故曰九针。人皮应天，人肉应地，人脉应人，人筋应时，人声应音，人阴阳合气应律，人齿面目应星，人出入气应风，人九窍三百六十五络应野。故一针皮，二针肉，三针脉，四针筋，五针骨，六针调阴阳，七针益精，八针除风，九针通九窍，除三百六十五节气，此之谓各有所主也。')
add('注释', '13.5.1.5', '"刺虚则实之者，针下热也…满而泄之者，针下寒也"：以针下寒热验补写——①以得气之寒热感释（补之针下热，写之针下寒，通行）；②有注家认为"针下热/寒"为患者主观感觉或医者触觉之辨——并存（非零和局）。又"人皮应天…九窍三百六十五络应野"——九针应九数之天人相应观。')

