add('篇名', '7.5', '太阴阳明论（素问第29篇）')
add('通读', '7.5.0', '通读：本篇为脾胃理论之专论——论太阴（脾）阳明（胃）相为表里、各因其经而生病，提出"脾为胃行其津液""四肢皆禀气于胃而不得至经，必因于脾乃得禀也"之脾胃枢纽论，为"脾胃后天之本"思想之渊薮。')
add('原文', '7.5.1.1', '黄帝问曰：太阴阳明为表里，脾胃脉也。生病而异者何也？岐伯对曰：阴阳异位，更虚更实，更逆更从，或从内，或从外，所从不同，故病异名也。帝曰：愿闻其异状也。岐伯曰：阳者，天气也，主外；阴者，地气也，主内。故阳道实，阴道虚。故犯贼风虚邪者，阳受之；食饮不节，起居不时者，阴受之。阳受之则入六府，阴受之则入五藏。入六府则身热不时卧，上为喘呼；入五藏则䐜满闭塞，下为飧泄，久为肠澼。故喉主天气，咽主地气。故阳受风气，阴受湿气。故阴气从足上行至头，而下行循臂至指端；阳气从手上行至头，而下行至足。故曰：阳病者上行极而下，阴病者下行极而上。故伤于风者，上先受之；伤于湿者，下先受之。')
add('原文', '7.5.1.2', '帝曰：脾病而四支不用何也？岐伯曰：四支皆禀气于胃，而不得至经，必因于脾，乃得禀也。今脾病不能为胃行其津液，四支不得禀水谷气，气日以衰，脉道不利，筋骨肌肉，皆无气以生，故不用焉。')
add('原文', '7.5.1.3', '帝曰：脾不主时何也？岐伯曰：脾者土也，治中央，常以四时长四藏，各十八日寄治，不得独主于时也。脾脏者常著胃土之精也，土者生万物而法天地，故上下至头足，不得主时也。')
add('原文', '7.5.1.4', '帝曰：脾与胃以膜相连耳，而能为之行其津液何也？岐伯曰：足太阴者三阴也，其脉贯胃属脾络嗌，故太阴为之行气于三阴。阳明者表也，五藏六府之海也，亦为之行气于三阳。藏府各因其经而受气于阳明，故为胃行其津液。四支不得禀水谷气，日以益衰，阴道不利，筋骨肌肉无气以生，故不用焉。')
add('注释', '7.5.1.5', '"脾为胃行其津液"与"四支皆禀气于胃，必因于脾乃得禀"：脾胃枢纽论之核心，古今无异说。然"脾不主时，各十八日寄治"——①以脾土寄旺于四时之末各十八日释（通行）；②有学者认为"十八日寄治"为五行历法推演，与临床对应存疑——并存（非零和局）。本篇与主编邹纯朴"脾胃后天之本"临床主线高度契合。')

# ── 7.6 阳明脉解（第30篇）──
add('篇名', '7.6', '阳明脉解（素问第30篇）')
add('通读', '7.6.0', '通读：本篇专解阳明脉之病候——"阳明病则脉大，其病恶火、恶人、喘而惋、登高而歌、弃衣而走、骂詈不避亲疏"，以"阳盛则四肢实"释之，为阳明热盛发狂之病机专篇。')
add('原文', '7.6.1.1', '黄帝问曰：足阳明之脉病，恶人与火，闻木音则惕然而惊，钟鼓不为动。闻木音而惊何也？愿闻其故。岐伯对曰：阳明者胃脉也，胃者土也，故闻木音而惊者，土恶木也。帝曰：善。其恶火何也？岐伯曰：阳明主肉，其脉血气盛，邪客之则热，热甚则恶火。帝曰：其恶人何也？岐伯曰：阳明厥则喘而惋，惋则恶人。')
add('原文', '7.6.1.2', '帝曰：或喘而死者，或喘而生者，何也？岐伯曰：厥逆连藏则死，连经则生。')
add('原文', '7.6.1.3', '帝曰：善。病甚则弃衣而走，登高而歌，或至不食数日，逾垣上屋，所上之处，皆非其素所能也，病反能者何也？岐伯曰：四支者，诸阳之本也。阳盛则四支实，实则能登高也。帝曰：其弃衣而走者何也？岐伯曰：热盛于身，故弃衣欲走也。帝曰：其妄言骂詈不避亲疏而歌者何也？岐伯曰：阳盛则使人妄言骂詈不避亲疏，而不欲食，不欲食故妄走也。')
add('注释', '7.6.1.4', '"闻木音而惊者，土恶木也"：以五行相克（木克土）释惊——①以五行释（通行）；②有以"阳明厥则喘而惋"之病理释，谓惊为气逆所致。二说并存（非零和局）。又"登高而歌，弃衣而走"——阳明热盛神昏之象，今以感染中毒性脑病/谵妄相参，与古说互补。')

