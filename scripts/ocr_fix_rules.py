ZHI_SECTION_V = ['浩法', '洛法', '浴法', '沼法', '滘法', '照法']

# ③ 正则规则
RX_LIAO = re.compile(r'(?<![治医疗])疗(?!法|效|程)')          # 疗→疔，保护 治疗/医疗/疗法


def safe_t2s(s):
    """繁→简；目标不在常用汉字区(U+4E00–9FFF)者保留原字形（防豆腐块）"""
    if not s:
        return s
    o = t2s.convert(s)
    if len(o) != len(s):
        return o
    return ''.join(a if (a != c and not (0x4E00 <= ord(c) <= 0x9FFF)) else c
                   for a, c in zip(s, o))


def fix(s):
    """应用全部校字规则（含 t2s、段标记归一、循环处理相邻情形）"""
    if not s:
        return s
    o = safe_t2s(s)
    o = RX_MARK_LOST.sub(lambda m: '【丁痂皮】' if m.group(0).startswith('丁皮') else '【丁奚疳】', o)
    for v in BOOKNAME_V[1:]:                  # 书眉「病源辞典」讹形归一（长串优先）
        if v in o:
            o = o.replace(v, '病源辞典')
    for a, b in SEQ:
        if a in o:
            o = o.replace(a, b)
    for v in SRC_SECTION_V:                 # 病达/病然/… → 病状
        if v in o:
            o = o.replace(v, '病状')
    for v in ZHI_SECTION_V:                 # 浩法/洛法/… → 治法
        if v in o:
            o = o.replace(v, '治法')
    for _ in range(4):                       # 循环至稳定（处理相邻，如「疗疗」）
        if not RX_LIAO.search(o):
            break
        o = RX_LIAO.sub('疔', o)
    return o
