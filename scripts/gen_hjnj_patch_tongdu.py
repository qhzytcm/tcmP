ch_sheets = ['1.素问·养生总纲','2.素问·阴阳学说','3.素问·藏象','4.素问·诊法总论','5.素问·脉学']

def insert_after(ws, row_idx, cat, code, text):
    """在 row_idx 行后插入一行"""
    ws.insert_rows(row_idx + 1)
    ws.cell(row=row_idx + 1, column=1, value=cat)
    ws.cell(row=row_idx + 1, column=2, value=code)
    ws.cell(row=row_idx + 1, column=3, value=text)

added_tongdu = added_note = 0
for s in ch_sheets:
    ws = wb[s]
    # 收集 (行号, 类型, 篇名) 以便插入
    # 注意: 插入会改变行号, 从后往前插
    insert_points = []  # (行号, 篇名)
    for row in ws.iter_rows(min_row=2, max_col=3):
        if row[0].value == '篇名' and row[2].value:
            pn = str(row[2].value).split('（')[0].strip()
            insert_points.append((row[0].row, pn))
    # 从后往前插入, 行号不冲突
    for row_idx, pn in reversed(insert_points):
        td = TONGDU.get(pn)
        if td:
            # 通读行编码: 篇名行后插, 编码用篇名行的节号 + .0
            sec_code = ws.cell(row=row_idx, column=2).value  # 如 '1.1'
            insert_after(ws, row_idx, '通读', f'{sec_code}.0', td)
            added_tongdu += 1
    # 补注释: 追加到各篇段落后（篇名行之后若干行）
    # 重新扫描（行号已变）, 找到对应篇注释不足的行尾
    note_points = []  # (插入行号, 篇名)
    cur_pn = None
    rows_data = [(row[0].row, row[0].value, row[1].value, row[2].value) for row in ws.iter_rows(min_row=2, max_col=3)]
    for r, cat, code, val in rows_data:
        if cat == '篇名' and val:
            cur_pn = str(val).split('（')[0].strip()
            note_points.append((r, cur_pn))  # 记录篇名行
    # 找每篇最后一行, 在其后插入注释
    last_row_of_pian = {}
    for r, cat, code, val in rows_data:
        for pr, pn in note_points:
            if r >= pr:
                last_row_of_pian[pn] = r
    for pn, note in NOTES.items():
        if pn in last_row_of_pian:
            insert_after(ws, last_row_of_pian[pn], '注释', f'{ws.cell(row=last_row_of_pian[pn], column=2).value.split(".")[0]}.{pn}补', note)
            added_note += 1

wb.save(PATH)
print(f"已补齐: 通读 {added_tongdu} 行, 注释 {added_note} 行")
print(f"Sheet: {wb.sheetnames}")
