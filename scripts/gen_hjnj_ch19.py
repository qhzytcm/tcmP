add('原文', '19.3.1.1', '凡刺之要，官针最妙。九针之宜，各有所为，长短大小，各有所施也。不得其用，病弗能移。疾浅针深，内伤良肉，皮肤为痈；病深针浅，病气不写，支为大脓。病小针大，气写太甚，疾必为害；病大针小，气不泄写，亦复为败。失针之宜，大者写，小者不移。已言其过，请言其所施。')
add('原文', '19.3.1.2', '病在皮肤无常处者，取以镵针于病所，肤白勿取。病在分肉间，取以员针于病所。病在经络痼痹者，取以锋针。病在脉，气少当补之者，取以鍉针于井荥分俞。病为大脓者，取以铍针。病痹气暴发者，取以员利针。病痹气痛而不去者，取以毫针。病在中者，取以长针。病水肿不能通关节者，取以大针。病在五藏固居者，取以锋针，写于井荥分俞，取以四时。')
add('原文', '19.3.1.3', '凡刺有九，以应九变。一曰输刺。输刺者，刺诸经荥俞藏俞也。二曰远道刺。远道刺者，病在上，取之下，刺府俞也。三曰经刺。经刺者，刺大经之结络经分也。四曰络刺。络刺者，刺小络之血脉也。五曰分刺。分刺者，刺分肉之间也。六曰大写刺。大写刺者，刺大脓以铍针也。七曰毛刺。毛刺者，刺浮痹皮肤也。八曰巨刺。巨刺者，左取右，右取左。九曰焠刺。焠刺者，刺燔针则取痹也。')
add('原文', '19.3.1.4', '凡刺有十二节，以应十二经。一曰偶刺。偶刺者，以手直心若背，直痛所，一刺前，一刺后，以治心痹。刺此者，傍针之也。二曰报刺。报刺者，刺痛无常处也。上下行者，直内无拔针，以左手随病所按之，乃出针复刺之也。三曰恢刺。恢刺者，直刺傍之，举之，前后恢筋急，以治筋痹也。四曰齐刺。齐刺者，直入一，傍入二，以治寒气小深者。或曰三刺。三刺者，治痹气小深者也。五曰扬刺。扬刺者，正内一，傍内四，而浮之，以治寒气之博大者也。六曰直针刺。直针刺者，引皮乃刺之，以治寒气之浅者也。七曰输刺。输刺者，直入直出，稀发针而深之，以治气盛而热者也。八曰短刺。短刺者，刺骨痹，稍摇而深之，致针骨所，以上下摩骨也。九曰浮刺。浮刺者，傍入而浮之，以治肌急而寒者也。十曰阴刺。阴刺者，左右率刺之，以治寒厥，中寒厥，足踝后少阴也。十一曰傍针刺。傍针刺者，直刺傍刺各一，以治留痹久居者也。十二曰赞刺。赞刺者，直入直出，数发针而浅之出血，是谓治痈肿也。')
add('原文', '19.3.1.5', '脉之所居深不见者，刺之微内针而久留之，以致其空脉气也。脉浅者勿刺，按绝其脉乃刺之，无令精出，独出其邪气耳。')
