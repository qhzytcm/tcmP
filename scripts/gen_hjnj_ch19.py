add('原文', '19.2.1.2', '少师答曰：阴中有阴，阳中有阳，审知阴阳，刺之有方。得病所始，刺之有理。谨度病端，与时相应。内合于五藏六府，外合于筋骨皮肤。是故内有阴阳，外亦有阴阳。在内者，五藏为阴，六府为阳；在外者，筋骨为阴，皮肤为阳。故曰：病在阴之阴者，刺阴之荥输；病在阳之阳者，刺阳之合；病在阳之阴者，刺阴之经；病在阴之阳者，刺络脉。故曰：病在阳者命曰风，病在阴者命曰痹，阴阳俱病命曰风痹。病有形而不痛者，阳之类也；无形而痛者，阴之类也。无形而痛者，其阳完而阴伤之也，急治其阴，无攻其阳。有形而不痛者，其阴完而阳伤之也，急治其阳，无攻其阴。阴阳俱动，乍有形，乍无形，加以烦心，命曰阴胜其阳，此谓不表不里，其形不久。')
