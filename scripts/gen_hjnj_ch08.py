# ── 8.3 评热病论（第33篇）──
add('篇名', '8.3', '评热病论（素问第33篇）')
add('通读', '8.3.0', '通读：本篇评论热病之变证——阴阳交（热病汗出复热，不能食者死）、风厥（汗出而身热，烦满不为汗解）、劳风（劳而受风，咳出青黄涕）与肾风（面胕庞然，不能正偃），辨析"正不胜邪""表里同病"之病机，为热病预后与病机分析之典范。')
add('原文', '8.3.1.1', '黄帝问曰：有病温者，汗出辄复热，而脉躁疾，不为汗衰，狂言不能食，病名为何？岐伯对曰：病名阴阳交，交者死也。帝曰：愿闻其说。岐伯曰：人所以汗出者，皆生于谷，谷生于精。今邪气交争于骨肉而得汗者，是邪却而精胜也。精胜则当能食而不复热。复热者，邪气也。汗者，精气也。今汗出而辄复热者，是邪胜也。不能食者，精无俾也。病而留者，其寿可立而倾也。且夫热论曰：汗出而脉尚躁盛者死。今脉不与汗相应，此不胜其病也，其死明矣。狂言者是失志，失志者死。今见三死，不见一生，虽愈必死也。')
add('原文', '8.3.1.2', '帝曰：有病身热汗出烦满，烦满不为汗解，此为何病？岐伯曰：汗出而身热者风也，汗出而烦满不解者厥也，病名曰风厥。帝曰：愿卒闻之。岐伯曰：巨阳主气，故先受邪，少阴与其为表里也，得热则上从之，从之则厥也。帝曰：治之奈何？岐伯曰：表里刺之，饮之服汤。')
add('原文', '8.3.1.3', '帝曰：有病劳风者，病在肺下，其为病也，使人强上冥视，唾出若涕，恶风而振寒，此为劳风之病。帝曰：治之奈何？岐伯曰：以救俯仰。巨阳引精者三日，中年者五日，不精者七日。咳出青黄涕，其状如脓，大如弹丸，从口中若鼻中出，不出则伤肺，伤肺则死也。')
add('原文', '8.3.1.4', '帝曰：有病肾风者，面胕庞然，壅害于言，可刺不？岐伯曰：虚不当刺，不当刺而刺，后五日其气必至。帝曰：其至何如？岐伯曰：至必少气时热，时热从胸背上至头，汗出，手热，口干苦渴，小便黄，目下肿，腹中鸣，身重难以行，月事不来，烦而不能食，不能正偃，正偃则咳，病名曰风水，论在《刺法》中。')
add('原文', '8.3.1.5', '帝曰：愿闻其说。岐伯曰：邪之所凑，其气必虚。阴虚者阳必凑之，故少气时热而汗出也。小便黄者，少腹中有热也。不能正偃者，胃中不和也。正偃则咳甚，上迫肺也。诸有水气者，微肿先见于目下也。')
add('原文', '8.3.1.6', '帝曰：何以言？岐伯曰：水者阴也，目下亦阴也，腹者至阴之所居，故水在腹者，必使目下肿也。真气上逆，故口苦舌干，卧不得正偃，正偃则咳出清水也。诸水病者，故不得卧，卧则惊，惊则咳甚也。腹中鸣者，病本于胃也。薄脾则烦不能食。食不下者，胃脘隔也。身重难以行者，胃脉在足也。月事不来者，胞脉闭也。胞脉者属心而络于胞中，今气上迫肺，心气不得下通，故月事不来也。')
add('注释', '8.3.1.7', '"邪之所凑，其气必虚"：千古名句，正气不足乃发病之内因——①以正虚邪凑释（通行）；②有学者强调"凑"当读"奏"（趋会），谓邪气趋会于虚处，与"两虚相感"义通。并存（非零和局）。又"阴阳交"之三死（汗出复热/不能食/狂言失志）——热病危候之辨，诸家无异说。')

# ── 8.4 逆调论（第34篇）──
add('篇名', '8.4', '逆调论（素问第34篇）')
add('通读', '8.4.0', '通读：本篇论"逆调"之病——寒热逆调（人非常温/非常寒）、肉烁（肌肉消瘦）、肉苛（肌肉麻木不仁）、骨痹（骨寒）、气逆（不得卧而喘）等阴阳逆乱之证，提出"不得卧而息有音者，是阳明之逆也"等病机，为阴阳失调辨证之范例。')
add('原文', '8.4.1.1', '黄帝问曰：人身非常温也，非常热也，为之热而烦满者何也？岐伯对曰：阴气少而阳气胜，故热而烦满也。帝曰：人身非衣寒也，中非有寒气也，寒从中生者何？岐伯曰：是人多痹气也，阳气少，阴气多，故身寒如从水中出。')
add('原文', '8.4.1.2', '帝曰：人有四肢热，逢风寒如炙如火者何也？岐伯曰：是人者，阴气虚，阳气盛。四肢者阳也，两阳相得，而阴气虚少，少水不能灭盛火，而阳独治。独治者，不能生长也，独胜而止耳。逢风而如炙如火者，是人当肉烁也。')
add('原文', '8.4.1.3', '帝曰：人有身寒，汤火不能热，厚衣不能温，然不冻栗，是为何病？岐伯曰：是人者，素肾气胜，以水为事，太阳气衰，肾脂枯不长，一水不能胜两火。肾者水也，而生于骨，肾不生则髓不能满，故寒甚至骨也。所以不能冻栗者，肝一阳也，心二阳也，肾孤藏也，一水不能胜二火，故不能冻栗，病名曰骨痹，是人当挛节也。')
add('原文', '8.4.1.4', '帝曰：人之肉苛者，虽近衣絮，犹尚苛也，是为何疾？岐伯曰：荣气虚，卫气实也。荣气虚则不仁，卫气虚则不用，荣卫俱虚，则不仁且不用，肉如故也。人与志不相有，曰死。')
add('原文', '8.4.1.5', '帝曰：人有逆气不得卧而息有音者，有不得卧而息无音者，有起居如故而息有音者，有得卧行而喘者，有不得卧不能行而喘者，有不得卧卧而喘者。皆何藏使然？愿闻其故。岐伯曰：不得卧而息有音者，是阳明之逆也。足三阳者下行，今逆而上行，故息有音也。阳明者，胃脉也，胃者六府之海，其气亦下行。阳明逆，不得从其道，故不得卧也。《下经》曰：胃不和则卧不安。此之谓也。')
add('原文', '8.4.1.6', '夫起居如故而息有音者，此肺之络脉逆也。络脉不得随经上下，故留经而不行。络脉之病人也微，故起居如故而息有音也。夫不得卧，卧则喘者，是水气之客也。夫水者，循津液而流也。肾者水藏，主津液，主卧与喘也。帝曰：善。')
add('注释', '8.4.1.7', '"胃不和则卧不安"：①以阳明逆气、胃气不得下行释（卧不安因胃气逆）；②后世扩为"饮食不节/胃中不和致失眠"之通义（如《景岳全书》引申）；③今人以"胃食管反流/睡眠呼吸"相参。并存（非零和局）。又"肉苛"之荣卫俱虚——"人与志不相有曰死"（神志与形体不相应），诸家无异说。')

