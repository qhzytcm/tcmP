# ── 11.2 痹论（第43篇）──
add('篇名', '11.2', '痹论（素问第43篇）')
add('通读', '11.2.0', '通读：本篇为痹证之专论——"风寒湿三气杂至，合而为痹"，分行痹、痛痹、着痹及五脏痹、六腑痹（肠痹/胞痹），提出"凡痹之类，逢寒则虫，逢热则纵"与"痹在于骨则重，在于脉则血凝而不流"之病机，为痹证辨证之经典总纲。')
add('原文', '11.2.1.1', '黄帝问曰：痹之安生？岐伯对曰：风寒湿三气杂至，合而为痹也。其风气胜者为行痹，寒气胜者为痛痹，湿气胜者为着痹也。帝曰：其有五者何也？岐伯曰：以冬遇此者为骨痹，以春遇此者为筋痹，以夏遇此者为脉痹，以至阴遇此者为肌痹，以秋遇此者为皮痹。')
add('原文', '11.2.1.2', '帝曰：内舍五藏六府，何气使然？岐伯曰：五藏皆有合，病久而不去者，内舍于其合也。故骨痹不已，复感于邪，内舍于肾；筋痹不已，复感于邪，内舍于肝；脉痹不已，复感于邪，内舍于心；肌痹不已，复感于邪，内舍于脾；皮痹不已，复感于邪，内舍于肺。所谓痹者，各以其时重感于风寒湿之气也。')
add('原文', '11.2.1.3', '凡痹之客五藏者，肺痹者，烦满喘而呕。心痹者，脉不通，烦则心下鼓，暴上气而喘，嗌干善噫，厥气上则恐。肝痹者，夜卧则惊，多饮数小便，上为引如怀。肾痹者，善胀，尻以代踵，脊以代头。脾痹者，四支解堕，发咳呕汁，上为大塞。肠痹者，数饮而出不得，中气喘争，时发飧泄。胞痹者，少腹膀胱按之内痛，若沃以汤，涩于小便，上为清涕。')
add('原文', '11.2.1.4', '阴气者，静则神藏，躁则消亡。饮食自倍，肠胃乃伤。淫气喘息，痹聚在肺；淫气忧思，痹聚在心；淫气遗溺，痹聚在肾；淫气乏竭，痹聚在肝；淫气肌绝，痹聚在脾。诸痹不已，亦益内也。其风气胜者，其人易已也。')
add('原文', '11.2.1.5', '帝曰：痹，其时有死者，或疼久者，或易已者，其故何也？岐伯曰：其入藏者死，其留连筋骨间者疼久，其留皮肤间者易已。')
add('原文', '11.2.1.6', '帝曰：其客于六府者何也？岐伯曰：此亦其食饮居处，为其病本也。六府亦各有俞，风寒湿气中其俞，而食饮应之，循俞而入，各舍其府也。')
add('原文', '11.2.1.7', '帝曰：以针治之奈何？岐伯曰：五藏有俞，六府有合，循脉之分，各有所发，各随其过，则病瘳也。')
add('原文', '11.2.1.8', '帝曰：荣卫之气，亦令人痹乎？岐伯曰：荣者，水谷之精气也，和调于五藏，洒陈于六府，乃能入于脉也，故循脉上下，贯五藏，络六府也。卫者，水谷之悍气也，其气慓疾滑利，不能入于脉也，故循皮肤之中，分肉之间，熏于肓膜，散于胸腹。逆其气则病，从其气则愈。不与风寒湿气合，故不为痹。')
add('原文', '11.2.1.9', '帝曰：善。痹或痛，或不痛，或不仁，或寒，或热，或燥，或湿，其故何也？岐伯曰：痛者，寒气多也，有寒故痛也。其不痛不仁者，病久入深，荣卫之行涩，经络时疏，故不通。皮肤不营，故为不仁。其寒者，阳气少，阴气多，与病相益，故寒也。其热者，阳气多，阴气少，病气胜，阳遭阴，故为痹热。其多汗而濡者，此其逢湿甚也。阳气少，阴气盛，两气相感，故汗出而濡也。')
add('原文', '11.2.1.10', '帝曰：夫痹之为病，不痛何也？岐伯曰：痹在于骨则重，在于脉则血凝而不流，在于筋则屈不伸，在于肉则不仁，在于皮则寒。故具此五者，则不痛也。凡痹之类，逢寒则虫，逢热则纵。帝曰：善。')
add('注释', '11.2.1.11', '"风寒湿三气杂至，合而为痹"：痹证定义之经典总纲，千古无异说。然"逢寒则虫"之"虫"——①王冰训"虫"为"急"（寒则拘急）；②有训"虫"为"痛"（寒则痛甚）；③有认为"虫"为"痋"（疼痛）之借字——字训三说并存（非零和局）。又"饮食自倍，肠胃乃伤"——饮食不节致痹之本，为"病从口入"思想之肇端。')

# ── 11.3 痿论（第44篇）──
add('篇名', '11.3', '痿论（素问第44篇）')
add('通读', '11.3.0', '通读：本篇为痿证之专论——"五脏使人痿"（肺热叶焦则皮毛虚弱急薄着则生痿躄等），提出"治痿者独取阳明"之经典治则，论"阳明者，五藏六府之海，主闰宗筋，宗筋主束骨而利机关也"，为痿证辨证论治之渊源。')
add('原文', '11.3.1.1', '黄帝问曰：五藏使人痿何也？岐伯对曰：肺主身之皮毛，心主身之血脉，肝主身之筋膜，脾主身之肌肉，肾主身之骨髓。故肺热叶焦，则皮毛虚弱急薄，著则生痿躄也。心气热，则下脉厥而上，上则下脉虚，虚则生脉痿，枢折挈，胫纵而不任地也。肝气热，则胆泄口苦筋膜干，筋膜干则筋急而挛，发为筋痿。脾气热，则胃干而渴，肌肉不仁，发为肉痿。肾气热，则腰脊不举，骨枯而髓减，发为骨痿。')
add('原文', '11.3.1.2', '帝曰：何以得之？岐伯曰：肺热者色白而毛败，心热者色赤而络脉溢，肝热者色苍而爪枯，脾热者色黄而肉蠕动，肾热者色黑而齿槁。')
add('原文', '11.3.1.3', '帝曰：论言治痿者独取阳明何也？岐伯曰：阳明者，五藏六府之海，主闰宗筋，宗筋主束骨而利机关也。冲脉者，经脉之海也，主渗灌溪谷，与阳明合于宗筋。阴阳总宗筋之会，会于气街，而阳明为之长，皆属于带脉，而络于督脉。故阳明虚则宗筋纵，带脉不引，故足痿不用也。')
add('原文', '11.3.1.4', '帝曰：治之奈何？岐伯曰：各补其荥而通其俞，调其虚实，和其逆顺，筋脉骨肉，各以其时受月，则病已矣。帝曰：善。')
add('注释', '11.3.1.5', '"治痿者独取阳明"：痿证治则之经典——①以阳明为五脏六腑之海、主润宗筋释（独取阳明补益后天）；②后世有"独取阳明"非仅补益，亦含清阳明之热、通阳明之滞者——治则内涵之扩展并存（非零和局）。又"肺热叶焦"为痿之本——诸家无异说。')

# ── 11.4 厥论（第45篇）──
add('篇名', '11.4', '厥论（素问第45篇）')
add('通读', '11.4.0', '通读：本篇为厥证之专论——"阳气衰于下，则为寒厥；阴气衰于下，则为热厥"，论寒厥热厥之成因（秋冬夺于所用等）与六经厥、十二经厥逆之证候，提出"厥，或令人腹满，或令人暴不知人"之病机（气逆于上），为厥证辨证之经典。')
add('原文', '11.4.1.1', '黄帝问曰：厥之寒热者何也？岐伯对曰：阳气衰于下，则为寒厥；阴气衰于下，则为热厥。帝曰：热厥之为热也，必起于足下者何也？岐伯曰：阳气起于足五指之表，阴脉者集于足下而聚于足心，故阳气胜则足下热也。帝曰：寒厥之为寒也，必从五指而上于膝者何也？岐伯曰：阴气起于五指之里，集于膝下而聚于膝上，故阴气胜则从五指至膝上寒，其寒也，不从外，皆从内也。')
add('原文', '11.4.1.2', '帝曰：寒厥何失而然也？岐伯曰：前阴者，宗筋之所聚，太阴阳明之所合也。春夏则阳气多而阴气少，秋冬则阴气盛而阳气衰。此人者质壮，以秋冬夺于所用，下气上争，不能复，精气溢下，邪气因从之而上也。气因于中，阳气衰，不能渗营其经络，阳气日损，阴气独在，故手足为之寒也。')
add('原文', '11.4.1.3', '帝曰：热厥何如而然也？岐伯曰：酒入于胃，则络脉满而经脉虚，脾主为胃行其津液者也。阴气虚则阳气入，阳气入则胃不和，胃不和则精气竭，精气竭则不营其四支也。此人必数醉若饱以入房，气聚于脾中不得散，酒气与谷气相薄，热盛于中，故热遍于身，内热而溺赤也。夫酒气盛而慓悍，肾气有衰，阳气独胜，故手足为之热也。')
add('原文', '11.4.1.4', '帝曰：厥或令人腹满，或令人暴不知人，或至半日远至一日乃知人者何也？岐伯曰：阴气盛于上则下虚，下虚则腹胀满。阳气盛于上则下气重上，而邪气逆，逆则阳气乱，阳气乱则不知人也。')
add('原文', '11.4.1.5', '帝曰：善。愿闻六经脉之厥状病能也。岐伯曰：巨阳之厥，则肿首头重，足不能行，发为眴仆。阳明之厥，则癫疾欲走呼，腹满不得卧，面赤而热，妄见而妄言。少阳之厥，则暴聋颊肿而热，胁痛，胻不可以运。太阴之厥，则腹满䐜胀，后不利，不欲食，食则呕，不得卧。少阴之厥，则口干溺赤，腹满心痛。厥阴之厥，则少腹肿痛，腹胀，泾溲不利，好卧屈膝，阴缩肿，胻内热。盛则写之，虚则补之，不盛不虚，以经取之。')
add('原文', '11.4.1.6', '太阴厥逆，䯒急挛，心痛引腹，治主病者。少阴厥逆，虚满呕变，下泄清，治主病者。厥阴厥逆，挛腰痛，虚满前闭谵言，治主病者。三阴俱逆，不得前后，使人手足寒，三日死。太阳厥逆，僵仆呕血善衄，治主病者。少阳厥逆，机关不利，机关不利者，腰不可以行，项不可以顾，发肠痈不可治，惊者死。阳明厥逆，喘咳身热，善惊衄呕血。')
add('原文', '11.4.1.7', '手太阴厥逆，虚满而咳，善呕沫，治主病者。手心主少阴厥逆，心痛引喉，身热，死不可治。手太阳厥逆，耳聋泣出，项不可以顾，腰不可以俛仰，治主病者。手阳明少阳厥逆，发喉痹嗌肿，痉，治主病者。')
add('注释', '11.4.1.8', '"阳气衰于下，则为寒厥；阴气衰于下，则为热厥"：厥证阴阳盛衰之总纲。①以"下"为足（阳气起于足五指之表）释；②有注家以"下"指下焦（肾）释——"下"之指归二说并存（非零和局）。又"暴不知人"（厥之昏不知人）——以阳气乱于上释，为后世"气厥""尸厥"辨证之渊源。')

