add('原文', '11.1.1.3', '以春甲乙伤于风者为肝风，以夏丙丁伤于风者为心风，以季夏戊己伤于邪者为脾风，以秋庚辛中于邪者为肺风，以冬壬癸中于邪者为肾风。风中五藏六府之俞，亦为藏府之风。各入其门户所中，则为偏风。风气循风府而上，则为脑风。风入系头，则为目风眼寒。饮酒中风，则为漏风。入房汗出中风，则为内风。新沐中风，则为首风。久风入中，则为肠风飧泄。外在腠理，则为泄风。故风者，百病之长也。至其变化，乃为他病也，无常方，然致有风气也。')
add('原文', '11.1.1.4', '帝曰：五藏风之形状不同者何？愿闻其诊及其病能。岐伯曰：肺风之状，多汗恶风，色皏然白，时咳短气，昼日则差，暮则甚。诊在眉上，其色白。心风之状，多汗恶风，焦绝，善怒吓，赤色，病甚则言不可快。诊在口，其色赤。肝风之状，多汗恶风，善悲，色微苍，嗌干善怒，时憎女子。诊在目下，其色青。脾风之状，多汗恶风，身体怠惰，四支不欲动，色薄微黄，不嗜食。诊在鼻上，其色黄。肾风之状，多汗恶风，面痝然浮肿，脊痛不能正立，其色炲，隐曲不利。诊在肌上，其色黑。')
