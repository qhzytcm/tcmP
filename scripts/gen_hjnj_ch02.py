add('篇名', '2.2', '阴阳离合论（素问第6篇）')
add('原文', '2.2.1.1', '黄帝问曰：余闻天为阳，地为阴，日为阳，月为阴，大小月三百六十日成一岁，人亦应之。今三阴三阳，不应阴阳，其故何也？岐伯对曰：阴阳者，数之可十，推之可百，数之可千，推之可万，万之大不可胜数，然其要一也。天覆地载，万物方生，未出地者，命曰阴处，名曰阴中之阴；则出地者，命曰阴中之阳。阳予之正，阴为之主。故生因春，长因夏，收因秋，藏因冬，失常则天地四塞。阴阳之变，其在人者，亦数之可数。')
add('原文', '2.2.1.2', '帝曰：愿闻三阴三阳之离合也。岐伯曰：圣人南面而立，前曰广明，后曰太冲，太冲之地，名曰少阴，少阴之上，名曰太阳，太阳根起于至阴，结于命门，名曰阴中之阳。中身而上，名曰广明，广明之下，名曰太阴，太阴之前，名曰阳明，阳明根起于厉兑，名曰阴中之阳。厥阴之表，名曰少阳，少阳根起于窍阴，名曰阴中之少阳。是故三阳之离合也，太阳为开，阳明为阖，少阳为枢。三经者，不得相失也，搏而勿浮，命曰一阳。')
add('原文', '2.2.1.3', '帝曰：愿闻三阴。岐伯曰：外者为阳，内者为阴，然则中为阴，其冲在下，名曰太阴，太阴根起于隐白，名曰阴中之阴。太阴之后，名曰少阴，少阴根起于涌泉，名曰阴中之少阴。少阴之前，名曰厥阴，厥阴根起于大敦，阴之绝阳，名曰阴之绝阴。是故三阴之离合也，太阴为开，厥阴为阖，少阴为枢。三经者，不得相失也，搏而勿沉，名曰一阴。')
add('原文', '2.2.1.4', '阴阳𪫟𪫟，积传为一周，气里形表而为相成也。')
add('注释', '2.2.1.5', '“太阳为开，阳明为阖，少阳为枢”：开阖枢之义——①以门为喻（门之开合枢轴）；②以气机出入释（开主外出、阖主内入、枢主转输）。又三阴“太阴为开，厥阴为阖，少阴为枢”与之对。诸说并存，皆释经脉离合之机。')

