add('篇名', '9.3', '气厥论（素问第37篇）')
add('通读', '9.3.0', '通读：本篇论五脏六腑寒热之气相移所致之病——"肾移寒于肝，痈肿少气"等脏腑寒热相移之证，提出"寒气上逆""热气下迫"之传变病机，为"脏腑移热/移寒"病机之专论。')
add('原文', '9.3.1.1', '黄帝问曰：五藏六府，寒热相移者何？岐伯曰：肾移寒于肝，痈肿少气。脾移寒于肝，痈肿筋挛。肝移寒于心，狂隔中。心移寒于肺，肺消。肺消者，饮一溲二，死不治。肺移寒于肾，为涌水。涌水者，按腹不坚，水气客于大肠，疾行则鸣濯濯如囊裹浆，水之病也。')
add('原文', '9.3.1.2', '脾移热于肝，则为惊衄。肝移热于心，则死。心移热于肺，传为鬲消。肺移热于肾，传为柔痓。肾移热于脾，传为虚，肠澼死，不可治。胞移热于膀胱，则癃溺血。膀胱移热于小肠，鬲肠不便，上为口糜。小肠移热于大肠，为虑瘕，为沉。大肠移热于胃，善食而瘦入，谓之食亦。胃移热于胆，亦曰食亦。胆移热于脑，则辛頞鼻渊。鼻渊者，浊涕下不止也。传为衄蔑瞑目。故得之气厥也。')
add('注释', '9.3.1.3', '"肺消者，饮一溲二，死不治"：①以肺寒消烁、精气不固释（饮一溲二为津液直下）；②今人以"尿崩症/严重消渴"相参。并存（非零和局）。又"胆移热于脑，则辛頞鼻渊"——鼻渊（浊涕不止）病机之经典，与今鼻窦炎相参。')

