add('原文', '9.4.1.1', '黄帝问曰：肺之令人咳何也？岐伯对曰：五藏六府皆令人咳，非独肺也。帝曰：愿闻其状。岐伯曰：皮毛者，肺之合也。皮毛先受邪气，邪气以从其合也。其寒饮食入胃，从肺脉上至于肺，则肺寒，肺寒则外内合邪，因而客之，则为肺咳。五藏各以其时受病，非其时，各传以与之。')
add('原文', '9.4.1.2', '人与天地相参，故五藏各以治时感于寒，则受病，微则为咳，甚者为泄为痛。乘秋则肺先受邪，乘春则肝先受之，乘夏则心先受之，乘至阴则脾先受之，乘冬则肾先受之。')
add('原文', '9.4.1.3', '帝曰：何以异之？岐伯曰：肺咳之状，咳而喘息有音，甚则唾血。心咳之状，咳则心痛，喉中介介如梗状，甚则咽肿喉痹。肝咳之状，咳则两胁下痛，甚则不可以转，转则两胠下满。脾咳之状，咳则右胁下痛，阴阴引肩背，甚则不可以动，动则咳剧。肾咳之状，咳则腰背相引而痛，甚则咳涎。')
add('原文', '9.4.1.4', '帝曰：六府之咳奈何？安所受病？岐伯曰：五藏之久咳，乃移于六府。脾咳不已，则胃受之，胃咳之状，咳而呕，呕甚则长虫出。肝咳不已，则胆受之，胆咳之状，咳呕胆汁。肺咳不已，则大肠受之，大肠咳状，咳而遗失。心咳不已，则小肠受之，小肠咳状，咳而失气，气与咳俱失。肾咳不已，则膀胱受之，膀胱咳状，咳而遗溺。久咳不已，则三焦受之，三焦咳状，咳而腹满，不欲食饮。此皆聚于胃，关于肺，使人多涕唾而面浮肿气逆也。')
add('原文', '9.4.1.5', '帝曰：治之奈何？岐伯曰：治藏者治其俞，治府者治其合，浮肿者治其经。帝曰：善。')
add('注释', '9.4.1.6', '"五脏六腑皆令人咳，非独肺也"：咳嗽病机之总纲——①以五脏各以其时受病、移于六府释（通行）；②"聚于胃，关于肺"为咳之病机关键（脾胃为生痰之源，肺为贮痰之器）——此二句为后世"治咳不止于肺而重在脾胃"之渊源。又"长虫出"之"长虫"——或释蛔虫，或释为"呕甚则虫出"之泛指——并存（非零和局）。')

