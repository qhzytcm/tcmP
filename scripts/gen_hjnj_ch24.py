add('原文', '24.5.1.1', '黄帝问于岐伯曰：余闻刺法于夫子，夫子之所言，不离于营卫血气。夫十二经脉者，内属于府藏，外络于肢节，夫子乃合之于四海乎？岐伯答曰：人亦有四海，十二经水。经水者，皆注于海，海有东西南北，命曰四海。')
add('原文', '24.5.1.2', '黄帝曰：以人应之奈何？岐伯曰：人有髓海，有血海，有气海，有水谷之海，凡此四者，以应四海也。')
