add('原文', '24.5.1.4', '黄帝曰：定之奈何？岐伯曰：胃者水谷之海，其输上在气街，下至三里。冲脉者为十二经之海，其输上在于大杼，下出于巨虚之上下廉。膻中者为气之海，其输上在于柱骨之上下，前在于人迎。脑为髓之海，其输上在于其盖，下在风府。')
add('原文', '24.5.1.5', '黄帝曰：凡此四海者，何利何害？何生何败？岐伯曰：得顺者生，得逆者败；知调者利，不知调者害。')
add('原文', '24.5.1.6', '黄帝曰：四海之逆顺奈何？岐伯曰：气海有余者，气满胸中，悗息面赤；气海不足，则气少不足以言。血海有余，则常想其身大，怫然不知其所病；血海不足，亦常想其身小，狭然不知其所病。水谷之海有余，则腹满；水谷之海不足，则饥不受谷食。髓海有余，则轻劲多力，自过其度；髓海不足，则脑转耳鸣，胫酸眩冒，目无所见，懈怠安卧。')
