add('原文', '16.8.1.2', '帝曰：愿卒闻之。岐伯曰：升之不前，即有甚凶也。木欲升而天柱窒抑之，木欲发郁亦须待时，当刺足厥阴之井。火欲升而天蓬窒抑之，火欲发郁亦须待时，君火相火同刺包络之荥。土欲升而天冲窒抑之，土欲发郁亦须待时，当刺足太阴之俞。金欲升而天英窒抑之，金欲发郁亦须待时，当刺手太阴之经。水欲升而天芮窒抑之，水欲发郁亦须待时，当刺足少阴之合。')
add('原文', '16.8.1.3', '黄帝问曰：升降之刺，以知其要，愿闻司天未得迁正，使司化之失其常政，即万化之或其皆妄。然与民为病，可得先除，欲济群生，愿闻其说。岐伯稽首再拜曰：悉乎哉问！言其至理，圣念慈悯，欲济群生，臣乃尽陈斯道，可申洞微。')
add('原文', '16.8.1.4', '黄帝问曰：刚柔二干，失守其位，使天运之气皆虚乎？与民为病，可得平乎？岐伯曰：深乎哉问！明其奥旨，天地迭移，三年化疫，是谓根之可见，必有逃门。')
add('原文', '16.8.1.5', '假令甲子，刚柔失守，刚未正，柔孤而有亏，时序不令，即音律非从。如此三年，变生大疫。详其微甚，察其浅深，欲至而可刺，刺之当知其方。')
add('原文', '16.8.1.6', '黄帝问曰：余闻五疫之至，皆相染易，无问大小，病状相似，不施救疗，如何可得不相移易者？岐伯曰：不相染者，正气存内，邪不可干，避其毒气。天牝从来，复得其往，气出于脑，即不邪干。')
add('原文', '16.8.1.7', '黄帝问曰：人虚即神游失守位，使鬼神外干，是致夭亡，何以全真？愿闻刺法。岐伯稽首再拜曰：昭乎哉问！谓神移失守，虽在其体，然不致死，或有邪干，故令夭寿。只如厥阴失守，天以虚，人气肝虚，感天重虚，即魂游于上，邪干厥大气，身温犹可刺之，刺其足少阳之所过，复刺肝之俞。')
add('原文', '16.8.1.8', '人病心虚，又遇君相二火司天失守，感而三虚，遇火不及，黑尸鬼犯之，令人暴亡，可刺手少阳之所过，复刺心俞。人脾病，又遇太阴司天失守，感而三虚，又遇土不及，青尸鬼犯之，令人暴亡，可刺足阳明之所过，复刺脾之俞。人肺病，遇阳明司天失守，感而三虚，又遇金不及，赤尸鬼犯之，令人暴亡，可刺手阳明之所过，复刺肺俞。人肾病，又遇太阳司天失守，感而三虚，又遇水运不及之年，黄尸鬼犯之，令人暴亡，可刺足太阳之所过，复刺肾俞。')
add('注释', '16.8.1.9', '"正气存内，邪不可干，避其毒气"：遗篇之名句——①以扶正（正气存内）与避邪（避其毒气）并举释（通行），为疫病防治思想之经典；②"五疫之至，皆相染易，无问大小，病状相似"——疫病传染性之最早描述之一。又刺法论/本病论为宋代刘温舒补入之遗篇，其真伪历代有争议（或以为古传，或以为宋人补缀）——并存（非零和局），然其学术价值为后世（尤其疫病学）所重。')

