add('篇名', '26.7', '本脏（灵枢第47篇）')
add('通读', '26.7.0', '通读：本篇论脏腑之"本"（质）——"志意和则精神专直，魂魄不散，悔怒不起，五藏不受邪矣"，辨五脏六腑之小大高下坚脆端正偏倾及其病（心小则安，邪弗能伤等），提出"五藏皆小者，少病，苦焦心，大愁忧"等五藏皆小/大/高/下/坚/脆/端正/偏倾之候，为脏腑体质学之专论。')
add('原文', '26.7.1.1', '黄帝问于岐伯曰：人之血气精神者，所以奉生而周于性命者也。经脉者，所以行血气而营阴阳，濡筋骨，利关节者也。卫气者，所以温分肉，充皮肤，肥腠理，司开阖者也。志意者，所以御精神，收魂魄，适寒温，和喜怒者也。是故血和则经脉流行，营复阴阳，筋骨劲强，关节清利矣。卫气和则分肉解利，皮肤调柔，腠理致密矣。志意和则精神专直，魂魄不散，悔怒不起，五藏不受邪矣。寒温和则六府化谷，风痹不作，经脉通利，肢节得安矣。此人之常平也。')
add('原文', '26.7.1.2', '五藏者，所以藏精神血气魂魄者也。六府者，所以化水谷而行津液者也。此人之所以具受于天也，无愚智贤不肖，无以相倚也。然有其独尽天寿，而无邪僻之病，百年不衰，虽犯风雨卒寒大暑，犹有弗能害也。有其不离屏蔽室内，无怵惕之恐，然犹不免于病，何也？愿闻其故。')
add('原文', '26.7.1.3', '岐伯对曰：窘乎哉问也！五藏者，所以参天地，副阴阳，而连四时，化五节者也。五藏者，固有小大高下坚脆端正偏倾者，六府亦有小大长短厚薄结直缓急。凡此二十五者，各不同，或善或恶，或吉或凶，请言其方。')
add('原文', '26.7.1.4', '心小则安，邪弗能伤，易伤以忧；心大则忧不能伤，易伤于邪。心高则满于肺中，悗而善忘，难开以言；心下则藏外，易伤于寒，易恐以言。心坚则藏安守固；心脆则善病消瘅热中。心端正则和利难伤；心偏倾则操持不一，无守司也。')
add('原文', '26.7.1.5', '肺小则少饮，不病喘喝；肺大则多饮，善病胸痹喉痹逆气。肺高则上气肩息咳；肺下则居贲迫肺，善胁下痛。肺坚则不病咳上气；肺脆则苦病消瘅易伤。肺端正则和利难伤；肺偏倾则胸偏痛也。')
add('原文', '26.7.1.6', '肝小则藏安，无胁下之病；肝大则逼胃迫咽，迫咽则苦膈中，且胁下痛。肝高则上支贲，切胁悗，为息贲；肝下则逼胃，胁下空，胁下空则易受邪。肝坚则藏安难伤；肝脆则善病消瘅易伤。肝端正则和利难伤；肝偏倾则胁下痛也。')
add('原文', '26.7.1.7', '脾小则藏安，难伤于邪也；脾大则苦凑䏚而痛，不能疾行。脾高则䏚引季胁而痛；脾下则下归于大肠，下归于大肠则善病飧泄。脾坚则藏安难伤；脾脆则善病消瘅易伤。脾端正则和利难伤；脾偏倾则善满善胀也。')
add('原文', '26.7.1.8', '肾小则藏安难伤；肾大则善病腰痛，不可以俛仰，易伤以邪。肾高则苦背膂痛，不可以俛仰；肾下则腰尻痛，不可以俛仰，为狐疝。肾坚则不病腰背痛；肾脆则善病消瘅易伤。肾端正则和利难伤；肾偏倾则苦腰尻痛也。')
add('原文', '26.7.1.9', '凡此二十五变者，人之所苦常病也。')
add('原文', '26.7.1.10', '黄帝曰：何以知其然也？岐伯曰：赤色小理者，心小；粗理者，心大。无𩪯𩪯者，心高；𩪯𩪯小短举者，心下。𩪯𩪯长者，心下坚；𩪯𩪯弱小以薄者，心脆。𩪯𩪯直下不举者，心端正；𩪯𩪯倚一方者，心偏倾也。')
add('原文', '26.7.1.11', '白色小理者，肺小；粗理者，肺大。巨肩反膺陷喉者，肺高；合腋张胁者，肺下。好肩背厚者，肺坚；肩背薄者，肺脆。背膺厚者，肺端正；胁偏疏者，肺偏倾也。')
add('原文', '26.7.1.12', '青色小理者，肝小；粗理者，肝大。广胸反骹者，肝高；合胁兔骹者，肝下。胸胁好者，肝坚；肋骨弱者，肝脆。膺腹好相得者，肝端正；肋骨偏举者，肝偏倾也。')
