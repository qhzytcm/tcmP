add('通读', '26.6.0', '通读：本篇论"五变"（人之质异而病异）——"一时遇风，同时得病，其病各异"，以"木之阴阳"（木之早凋/易折等）喻人之质，辨"肉不坚，腠理疏，则善病风""五藏皆柔弱者，善病消瘅""小骨弱肉者，善病寒热""粗理而肉不坚者，善病痹""皮肤薄而不泽，肉不坚而淖泽者，善病肠痹"等五变之质，为体质与发病之专论。')
add('原文', '26.6.1.1', '黄帝问于少俞曰：余闻百疾之始期也，必生于风雨寒暑，循毫毛而入腠理，或复还，或停留，或为风肿汗出，或为消瘅，或为寒热，或为留痹，或为积聚，奇邪淫溢，不可胜数，愿闻其故。夫同时得病，或病此，或病彼，意者天之为人生风乎，何其异也？')
add('原文', '26.6.1.2', '少俞曰：夫天之生风者，非以私百姓也，其行公平正直，犯者得之，避者得无殆，非求人而人自犯之。')
add('原文', '26.6.1.3', '黄帝曰：一时遇风，同时得病，其病各异，愿闻其故。少俞曰：善乎哉问！请论以比匠人。匠人磨斧斤，砺刀削，斫材木。木之阴阳，尚有坚脆，坚者不入，脆者皮弛，至其交节，而缺斤斧焉。夫一木之中，坚脆不同，坚者则刚，脆者易伤，况其材木之不同，皮之厚薄，汁之多少，而各异耶。夫木之早花先生叶者，遇春霜烈风，则花落而叶萎。久曝大旱，则脆木薄皮者，枝条汁少而叶萎。久阴淫雨，则薄皮多汁者，皮溃而漉。卒风暴起，则刚脆之木，枝折杌伤。秋霜疾风，则刚脆之木，根摇而叶落。凡此五者，各有所伤，况于人乎？')
add('原文', '26.6.1.4', '黄帝曰：以人应木奈何？少俞答曰：木之所伤也，皆伤其枝。枝之刚脆而坚，未成伤也。人之有常病也，亦因其骨节皮肤腠理之不坚固者，邪之所舍也，故常为病也。')
add('原文', '26.6.1.5', '黄帝曰：人之善病风厥漉汗者，何以候之？少俞答曰：肉不坚，腠理疏，则善病风。黄帝曰：何以候肉之不坚也？少俞答曰：䐃肉不坚，而无分理。理者粗理，粗理而皮不致者，腠理疏。此言其浑然者。')
add('原文', '26.6.1.6', '黄帝曰：人之善病消瘅者，何以候之？少俞答曰：五藏皆柔弱者，善病消瘅。黄帝曰：何以知五藏之柔弱也？少俞答曰：夫柔弱者，必有刚强，刚强多怒，柔者易伤也。黄帝曰：何以候柔弱之与刚强？少俞答曰：此人薄皮肤，而目坚固以深者，长冲直扬，其心刚，刚则多怒，怒则气上逆，胸中蓄积，血气逆留，䐜皮充肌，血脉不行，转而为热，热则消肌肤，故为消瘅。此言其人暴刚而肌肉弱者也。')
add('原文', '26.6.1.7', '黄帝曰：人之善病寒热者，何以候之？少俞答曰：小骨弱肉者，善病寒热。黄帝曰：何以候骨之小大，肉之坚脆，色之不一也？少俞答曰：颧骨者，骨之本也。颧大则骨大，颧小则骨小。皮肤薄而其肉无䐃，其臂懦懦然，其地色殆然，不与其天同色，污然独异，此其候也。然后臂薄者，其髓不满，故善病寒热也。')
add('原文', '26.6.1.8', '黄帝曰：何以候人之善病痹者？少俞答曰：粗理而肉不坚者，善病痹。黄帝曰：痹之高下有处乎？少俞答曰：欲知其高下者，各视其部。')
add('原文', '26.6.1.9', '黄帝曰：人之善病肠中积聚者，何以候之？少俞答曰：皮肤薄而不泽，肉不坚而淖泽，如此则肠胃恶，恶则邪气留止，积聚乃伤脾胃之间，寒温不次，邪气稍至，稸积留止，大聚乃起。')
add('注释', '26.6.1.10', '本篇注释：①"一时遇风，同时得病，其病各异"——同邪异病（通行），为体质发病观之经典。②"木之阴阳，尚有坚脆……凡此五者，各有所伤，况于人乎"——以木喻人之五变（通行）。③"肉不坚，腠理疏，则善病风；五藏皆柔弱者，善病消瘅；小骨弱肉者，善病寒热；粗理而肉不坚者，善病痹；皮肤薄而不泽……善病肠中积聚"——五变之质（通行）。④"颧骨者，骨之本也"——以颧候骨（通行）。')

