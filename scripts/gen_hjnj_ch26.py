add('原文', '26.4.1.6', '黄帝曰：愿闻五变。岐伯曰：肝为牡藏，其色青，其时春，其音角，其味酸，其日甲乙。心为牡藏，其色赤，其时夏，其音徵，其味苦，其日丙丁。脾为牝藏，其色黄，其时长夏，其音宫，其味甘，其日戊己。肺为牝藏，其色白，其时秋，其音商，其味辛，其日庚辛。肾为牝藏，其色黑，其时冬，其音羽，其味咸，其日壬癸。')
