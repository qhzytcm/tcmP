add('通读', '26.4.0', '通读：本篇论一日分四时——"春生夏长，秋收冬藏，是气之常也，人亦应之。以一日分为四时，朝则为春，日中为夏，日入为秋，夜半为冬"，论"百病者，多以旦慧昼安，夕加夜甚"之时间节律（朝则人气始生，病气衰，故旦慧等）与"藏主冬，冬刺井"等五变主五输、五输应四时之刺法，为时间医学（昼夜节律）之专论。')
add('原文', '26.4.1.1', '黄帝曰：夫百病之所始生者，必起于燥湿寒暑风雨，阴阳喜怒，饮食居处。气合而有形，得藏而有名，余知其然也。夫百病者，多以旦慧昼安，夕加夜甚，何也？岐伯曰：四时之气使然。')
add('原文', '26.4.1.2', '黄帝曰：愿闻四时之气。岐伯曰：春生夏长，秋收冬藏，是气之常也，人亦应之。以一日分为四时，朝则为春，日中为夏，日入为秋，夜半为冬。朝则人气始生，病气衰，故旦慧；日中人气长，长则胜邪，故安；夕则人气始衰，邪气始生，故加；夜半人气入藏，邪气独居于身，故甚也。')
add('原文', '26.4.1.3', '黄帝曰：其时有反者何也？岐伯曰：是不应四时之气，藏独主其病者，是必以藏气之所不胜时者甚，以其所胜时者起也。')
add('原文', '26.4.1.4', '黄帝曰：治之奈何？岐伯曰：顺天之时，而病可与期。顺者为工，逆者为粗。')
