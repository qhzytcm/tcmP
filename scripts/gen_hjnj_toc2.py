def emit_pian(ch_no, pian, n):
    """输出一篇: 节=篇目, 小节=主题, 段落=落点(+通读)"""
    no, name, topic, luodian = pian
    # 节: 篇号.篇序
    sec = f'{ch_no}.{n}'
    lines.append(f'{sec} {name}（第{no}篇）')
    # 小节1: 主题
    sub1 = f'{sec}.1'
    lines.append(f'{sub1} {topic}')
    # 段落1.1: 通读
    lines.append(f'{sub1}.1 通读：{name}要旨与原文脉络')
    # 段落1.2: 落点
    lines.append(f'{sub1}.2 注释钩沉：{luodian}')
    # 小节2: 临床/针法应用
    sub2 = f'{sec}.2'
    lines.append(f'{sub2} 应用（养生康复）' if ch_no <= 17 else f'{sub2} 应用（经络针灸）')
    lines.append(f'{sub2}.1 临床钩沉与病案联系')
    lines.append(f'{sub2}.2 平台落点：知识图谱/概念向量表')

