# ═══ 25.4 血络论（灵枢第39篇）═══
add('篇名', '25.4', '血络论（灵枢第39篇）')
add('通读', '25.4.0', '通读：本篇论血络之刺——"脉之所注，血络之所注"，辨"刺血络而仆者""血出而射者""血出黑而浊者""血出清而半为汁者""发针而肿者""发针而面色脱色者""出血多而不动摇者"等刺血络之奇邪反应，并论"脉气盛而血虚者，刺之则脱气，脱气则仆"之刺禁，为刺络放血之专论。')
add('原文', '25.4.1.1', '黄帝曰：愿闻其奇邪而不在经者。岐伯曰：血络是也。')
add('原文', '25.4.1.2', '黄帝曰：刺血络而仆者，何也？血出而射者，何也？血少黑而浊者，何也？血出清而半为汁者，何也？发针而肿者，何也？血出若多若少而面色苍苍者，何也？发针而面色不变而烦悗者，何也？多出血而不动摇者，何也？愿闻其故。')
add('原文', '25.4.1.3', '岐伯曰：脉气盛而血虚者，刺之则脱气，脱气则仆。血气俱盛而阴气多者，其血滑，刺之则射。阳气蓄积，久留而不写者，其血黑以浊，故不能射。新饮而液渗于络，而未合和于血也，故血出而汁别焉。其不新饮者，身中有水，久则为肿。阴气积于阳，其气因于络，故刺之血未出而气先行，故肿。阴阳之气，其新相得而未和合，因而写之，则阴阳俱脱，表里相离，故脱色而苍苍然。刺之血出多，色不变而烦悗者，刺络而虚经，虚经之属于阴者，阴脱故烦悗。阴阳相得而合为痹者，此为内溢于经，外注于络，如是者，阴阳俱有余，虽多出血而弗能虚也。')
add('原文', '25.4.1.4', '黄帝曰：相之奈何？岐伯曰：血脉者，盛坚横以赤，上下无常处，小者如针，大者如筋，则而写之万全也。故无失数矣。失数而反，各如其度。')
add('原文', '25.4.1.5', '黄帝曰：针入而肉着者，何也？岐伯曰：热气因于针，则针热，热则肉着于针，故转焉。')
add('注释', '25.4.1.6', '本篇注释：①"血络"为奇邪不在经者（通行）。②刺血络八问之机理（仆/射/黑浊/汁/肿/脱色/烦悗/不动摇）——刺络反应之详析（通行），为刺络放血之临床指导。③"脉气盛而血虚者，刺之则脱气，脱气则仆"——刺络之禁（通行）。④"血脉者，盛坚横以赤……则而写之万全也"——血络之候（通行）。')

