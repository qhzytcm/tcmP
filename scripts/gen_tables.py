def draw_table(title, header, rows, path):
    n_cols = len(header)
    col_w = [280, 90, 420, 460, 320] if n_cols == 5 else [300, 380, 460]
    if n_cols == 3 and '对比项' in header:
        col_w = [320, 640, 640]
    row_h = 52
    header_h = 62
    title_h = 90
    pad = 30
    W = sum(col_w) + pad * 2
    H = title_h + header_h + row_h * len(rows) + 20
    img = Image.new('RGB', (W, H), 'white')
    d = ImageDraw.Draw(img)
    f_t = ImageFont.truetype(FONT_B, 30)
    f_h = ImageFont.truetype(FONT_B, 24)
    f_c = ImageFont.truetype(FONT, 19)

    # 标题
    d.text((pad, 20), title, font=f_t, fill='#2c3e50')

    # 顶线（粗 3px）在 header 顶
    x0, x1 = pad, pad + sum(col_w)
    y = title_h
    d.line([x0, y, x1, y], fill='#000', width=3)
    # 栏目线（细 1.5px）在 header 底
    y_h = y + header_h
    d.line([x0, y_h, x1, y_h], fill='#000', width=2)
    # 底线（粗 3px）
    d.line([x0, H - 20, x1, H - 20], fill='#000', width=3)

    # header
    cx = pad
    for i, h in enumerate(header):
        d.text((cx + 10, y + 14), h, font=f_h, fill='#000')
        cx += col_w[i]
    # 行
    yy = y_h
    for r_i, row in enumerate(rows):
        cx = pad
        for i, cell in enumerate(row):
            d.text((cx + 10, yy + 12), cell, font=f_c,
                   fill='#333' if r_i % 2 == 0 else '#111')
            cx += col_w[i]
        yy += row_h
    img.save(path)
    print(f'生成: {path} ({W}x{H})')


