def level_of(x: float) -> str:
    """数值 → 区间标签 L1~L5"""
    x = max(0.0, min(1.0, x))
    for code, _, lo, hi in LEVELS:
        if lo <= x < hi:
            return code
    return 'L5'


def level_cn(code: str) -> str:
    for c, cn, _, _ in LEVELS:
        if c == code:
            return f'{c}{cn}'
    return code


def gauss(x: float, mu: float = 1.0, sigma: float = 0.42) -> float:
    """高斯归一化（framework_spec 契约：峰位 μ=1.0、带宽 σ=0.42）"""
    return math.exp(-((x - mu) ** 2) / (2 * sigma * sigma))


