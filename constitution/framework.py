def wuxing_relation(a: str, b: str) -> str:
    """a 与 b 的五行关系：同/生/被生/克/被克"""
    if a == b:
        return '同'
    if SHENG.get(a) == b:
        return '生'
    if SHENG.get(b) == a:
        return '被生'
    if KE.get(a) == b:
        return '克'
    if KE.get(b) == a:
        return '被克'
    return '无关'


